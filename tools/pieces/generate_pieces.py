"""Turns the piece SVGs in tools/pieces/cburnett/ into Kotlin path data for Compose.

The path data strings stay as they are (Compose parses SVG path syntax); this only
resolves the inherited fill and stroke attributes and turns circles into paths.

    python3 tools/pieces/generate_pieces.py
"""
import pathlib
import xml.etree.ElementTree as ET

HERE = pathlib.Path(__file__).parent
OUT = HERE.parent.parent / "ui/src/main/kotlin/com/kregosh/chessopenings/ui/board/PiecePaths.kt"
NS = "{http://www.w3.org/2000/svg}"
NAMES = {"K": "KING", "Q": "QUEEN", "R": "ROOK", "B": "BISHOP", "N": "KNIGHT", "P": "PAWN"}
# SVG defaults for the attributes we use.
DEFAULTS = {"fill": "#000", "stroke": "none", "stroke-width": "1", "stroke-linecap": "butt",
            "stroke-linejoin": "miter", "fill-rule": "nonzero"}


def color(value):
    if value == "none":
        return "null"
    v = value.lstrip("#")
    if len(v) == 3:
        v = "".join(c * 2 for c in v)
    return f"0xFF{v.upper()}"


def circle_path(c):
    cx, cy, r = (float(c.get(k)) for k in ("cx", "cy", "r"))
    return f"M{cx - r} {cy}a{r} {r} 0 1 0 {2 * r} 0a{r} {r} 0 1 0 {-2 * r} 0"


def walk(element, inherited, out):
    attrs = dict(inherited)
    for key in DEFAULTS:
        if element.get(key) is not None:
            attrs[key] = element.get(key)
    tag = element.tag.replace(NS, "")
    if tag in ("path", "circle"):
        d = element.get("d") if tag == "path" else circle_path(element)
        out.append(
            f'        PiecePath("{d}", fill = {color(attrs["fill"])}, stroke = {color(attrs["stroke"])}, '
            f'strokeWidth = {float(attrs["stroke-width"])}f, cap = "{attrs["stroke-linecap"]}", '
            f'join = "{attrs["stroke-linejoin"]}", evenOdd = {str(attrs["fill-rule"] == "evenodd").lower()}),'
        )
    for child in element:
        walk(child, attrs, out)


lines = [
    "// Generated by tools/pieces/generate_pieces.py from the cburnett pieces",
    "// (Colin M.L. Burnett, GPLv2+, via lichess-org/lila). Do not edit by hand.",
    "package com.kregosh.chessopenings.ui.board",
    "",
    "import com.kregosh.chessopenings.chess.Color",
    "import com.kregosh.chessopenings.chess.PieceType",
    "",
    "/** Drawing data of each piece on a 45 × 45 canvas. */",
    "internal val PIECE_PATHS: Map<Pair<Color, PieceType>, List<PiecePath>> = mapOf(",
]
for color_letter, color_name in (("w", "WHITE"), ("b", "BLACK")):
    for letter, name in NAMES.items():
        svg = ET.parse(HERE / "cburnett" / f"{color_letter}{letter}.svg").getroot()
        paths = []
        walk(svg, DEFAULTS, paths)
        lines.append(f"    (Color.{color_name} to PieceType.{name}) to listOf(")
        lines.extend(paths)
        lines.append("    ),")
lines.append(")")
OUT.write_text("\n".join(lines) + "\n")
print(f"wrote {OUT}")
